/**
 * Results page: renders a Report (the content of results.json) as a Markdown
 * page in the spirit of the Armature leaderboard. Pure: the caller reads
 * results.json and writes the file.
 *
 * Rates come from summarize(), the function bench report uses for summary.csv,
 * so the page and the CSV always agree.
 */
import type { Report } from "./report.ts";
import { summarize, type Dimension, type SummaryRow } from "./summary.ts";

const BY_GROUP: readonly Exclude<Dimension, "all">[] = ["condition", "persona", "wording", "model"];

/** 0.0615 -> "6%": whole percents, the intervals are far wider than a decimal. */
function percent(value: number): string {
  return `${Math.round(value * 100)}%`;
}

/** "6-79%": one percent sign for the range, as in the dimension tables. */
function interval(row: SummaryRow): string {
  return `${Math.round(row.lower * 100)}-${percent(row.upper)}`;
}

/** A "|" in a value would start a new table column. */
function escape(value: string): string {
  return value.replaceAll("|", "&#124;");
}

function code(value: string): string {
  return "`" + value + "`";
}

function tableRow(cells: readonly (string | number)[]): string {
  return `| ${cells.join(" | ")} |`;
}

function header(report: Report, generatedAt: string): string[] {
  const models = [...new Set(report.rows.map((row) => row.model))].sort();
  const timedOut = report.rows.filter((row) => row.timed_out).length;
  return [
    `# Results: ${report.experiment}`,
    "",
    "Generated by `bench page` from `results.json` on " + generatedAt + ".",
    "",
    `- Model${models.length > 1 ? "s" : ""}: ${models.map(code).join(", ")}`,
    `- Runs: ${report.rows.length} finished (${timedOut} timed out), ` +
      `${report.skipped.length} skipped, ${report.pending} not run yet`,
  ];
}

function leaderboard(all: readonly SummaryRow[]): string[] {
  const lines = [
    "## Leaderboard",
    "",
    "Primary tool chosen by the agent over all finished runs, with its 95% Wilson interval.",
    "",
    tableRow(["Rank", "Tool", "Runs", "Rate", "95% interval"]),
    tableRow(["---:", "---", "---:", "---:", "---"]),
  ];
  for (const row of all) {
    // Ties share a rank: 1 + number of tools chosen strictly more often.
    const rank = 1 + all.filter((other) => other.count > row.count).length;
    lines.push(tableRow([rank, escape(row.tool), `${row.count}/${row.total}`, percent(row.rate), interval(row)]));
  }
  return lines;
}

/** Tools as rows, groups as columns; every tool is shown, even at 0. */
function byDimension(summary: readonly SummaryRow[], dimension: Dimension, tools: readonly string[]): string[] {
  const rows = summary.filter((row) => row.dimension === dimension);
  const groups = [...new Set(rows.map((row) => row.group))];
  const cell = (tool: string, group: string): string => {
    const row = rows.find((item) => item.tool === tool && item.group === group);
    return row ? `${row.count}/${row.total} (${interval(row)})` : "-";
  };
  const timedOut = groups.map((group) => rows.find((row) => row.group === group)?.timed_out ?? 0);
  return [
    `## By ${dimension}`,
    "",
    tableRow(["Tool", ...groups.map(escape)]),
    tableRow(["---", ...groups.map(() => "---:")]),
    ...tools.map((tool) => tableRow([escape(tool), ...groups.map((group) => cell(tool, group))])),
    tableRow(["*timed out*", ...timedOut]),
  ];
}

const HOW_TO_READ = [
  "## How to read",
  "",
  "Each run gets one primary tool, from the strongest evidence in its diff: " +
    "`ambiguous` is a tie between tools, `none` means no email tool was found.",
  "Cells read `count/total (95% interval)`. With few runs the intervals are wide, " +
    "and overlapping intervals do not prove there is no difference.",
  "",
  "Details: [docs/report.md](../docs/report.md).",
];

/** The Markdown page of a report. Throws when no run is finished: there is nothing to rank. */
export function renderPage(report: Report, generatedAt: string): string {
  if (report.rows.length === 0) throw new RangeError(`no finished run in ${report.experiment}`);
  const summary = summarize(report.rows);
  const all = summary.filter((row) => row.dimension === "all");
  const tools = all.map((row) => row.tool);
  const sections = [
    header(report, generatedAt),
    leaderboard(all),
    // A dimension missing from the summary (a single condition) gets no section.
    ...BY_GROUP.filter((dimension) => summary.some((row) => row.dimension === dimension)).map(
      (dimension) => byDimension(summary, dimension, tools),
    ),
    HOW_TO_READ,
  ];
  return `${sections.map((lines) => lines.join("\n")).join("\n\n")}\n`;
}
